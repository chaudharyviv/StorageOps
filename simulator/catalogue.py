"""Metric catalogue: every metric the simulator can emit, generated from the simulator itself.

Regenerate docs/METRICS.md with `python -m simulator.catalogue` after changing the cluster,
the derived metrics, or any scenario's `extra_objects`.
"""

from __future__ import annotations

import argparse
from collections.abc import Iterable
from pathlib import Path

from contracts import ScenarioType, Variant
from simulator.cluster import ObjectSpec
from simulator.engine import simulate
from simulator.scenario import (
    DEFAULT_START,
    SCENARIO_DIRS,
    LabelSpec,
    ScenarioVariant,
    Split,
    load_scenario,
    scenario_files,
)

CATALOGUE_PATH = Path(__file__).parent.parent / "docs" / "METRICS.md"
HEADER = """# Metric catalogue

Every metric the simulator emits, with its unit and the object types that emit it.

This file is generated by `python -m simulator.catalogue`; do not edit it by hand. A test
fails if it drifts from what the simulator emits, including metrics declared by a scenario's
`extra_objects`.

| Metric | Unit | Object types |
| --- | --- | --- |
"""

Catalogue = dict[str, tuple[str, set[str]]]


def _probe(extra_objects: tuple[ObjectSpec, ...] = ()) -> ScenarioVariant:
    """A two-minute healthy run, used only to see which series the engine produces."""
    return ScenarioVariant(
        scenario=ScenarioType.AGGREGATE_FILLING,
        variant=Variant.MILD,
        split=Split.TRAIN,
        description="catalogue probe",
        start=DEFAULT_START,
        duration_minutes=2,
        effects=(),
        labels=(LabelSpec("aggr1", 0),),
        extra_objects=extra_objects,
    )


def emitted_metrics(dirs: Iterable[Path] = SCENARIO_DIRS) -> Catalogue:
    """Map metric name to (unit, object types), from the cluster and every scenario file."""
    probes = [_probe()]
    for path in scenario_files(dirs):
        probes += [_probe(v.extra_objects) for v in load_scenario(path).variants.values()]
    found: Catalogue = {}
    for probe in probes:
        result = simulate(probe, seed=0)
        for (object_type, _, metric), unit in result.units.items():
            known_unit, types = found.setdefault(metric, (unit, set()))
            if known_unit != unit:
                raise ValueError(f"metric {metric!r} has two units: {known_unit!r} and {unit!r}")
            types.add(object_type.value)
    return found


def render(catalogue: Catalogue) -> str:
    """Render the catalogue as the markdown table in docs/METRICS.md."""
    rows = [
        f"| `{metric}` | {unit} | {', '.join(sorted(types))} |"
        for metric, (unit, types) in sorted(catalogue.items())
    ]
    return HEADER + "\n".join(rows) + "\n"


def parse(text: str) -> Catalogue:
    """Read a catalogue back from markdown produced by render()."""
    found: Catalogue = {}
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`") and cells[0].endswith("`"):
            found[cells[0].strip("`")] = (cells[1], {t.strip() for t in cells[2].split(",")})
    return found


def main(argv: list[str] | None = None) -> int:
    """Write the catalogue file; return a process exit code."""
    parser = argparse.ArgumentParser(prog="python -m simulator.catalogue", description=__doc__)
    parser.add_argument("--out", type=Path, default=CATALOGUE_PATH)
    args = parser.parse_args(argv)
    args.out.write_text(render(emitted_metrics()), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
